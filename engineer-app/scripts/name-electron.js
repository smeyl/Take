// Give the development Electron.app Take's name and icon.
//
// `npm start` runs the stock Electron.app from node_modules, so macOS shows
// "Electron" as the Dock hover label, menu-bar title and Activity Monitor
// name, and Electron's icon in the app switcher and Activity Monitor — those
// come from the running bundle, which app.setName()/app.dock.setIcon() can't
// change. This rewrites that bundle's CFBundleName/CFBundleDisplayName to
// package.json's productName, swaps its icon for the engineer icon from
// Take Engineer.app, and re-registers it with LaunchServices. The bundle's
// ad-hoc signature binds neither Info.plist nor resources, so no re-signing
// is needed. Runs as a postinstall hook, so it survives `npm install`.
const { execFileSync } = require('child_process')
const fs = require('fs')
const path = require('path')

const LSREGISTER = '/System/Library/Frameworks/CoreServices.framework/Versions/A/' +
  'Frameworks/LaunchServices.framework/Versions/A/Support/lsregister'

if (process.platform !== 'darwin') process.exit(0)

const name = require('../package.json').productName
const bundle = path.join(__dirname, '..', 'node_modules', 'electron', 'dist', 'Electron.app')
const plist = path.join(bundle, 'Contents', 'Info.plist')
if (!fs.existsSync(plist)) {
  console.log(`name-electron: ${plist} not found — skipping`)
  process.exit(0)
}

for (const key of ['CFBundleName', 'CFBundleDisplayName']) {
  execFileSync('plutil', ['-replace', key, '-string', name, plist])
}

// Generated by assets/make_icons.py; electron.icns is the bundle's CFBundleIconFile.
const icon = path.join(__dirname, '..', '..', 'Take Engineer.app', 'Contents', 'Resources', 'AppIcon.icns')
if (fs.existsSync(icon)) {
  fs.copyFileSync(icon, path.join(bundle, 'Contents', 'Resources', 'electron.icns'))
} else {
  console.log(`name-electron: ${icon} not found — keeping Electron's icon`)
}
// macOS caches bundle names and icons; a fresh mtime plus re-registering makes
// it read them again (re-registering alone kept the cached Electron icon).
const now = new Date()
fs.utimesSync(bundle, now, now)
try {
  execFileSync(LSREGISTER, ['-f', bundle])
} catch (e) {
  console.log(`name-electron: couldn't re-register with LaunchServices (${e.message})`)
}
console.log(`name-electron: Electron.app now shows as "${name}" with the engineer icon`)
